    //Load method
    private void load() {
        txtArea_Display.setText("");;
        txtArea_Display.append("Total Sales: " + sales.GetTotalSales() + "\n");
         txtArea_Display.append(String.format("Average Sales: %.0f%n", sales.GetAverageSales()));
         txtArea_Display.append("Sales over target: " + sales.GetSalesOverTarget() + "\n");
         txtArea_Display.append("Sales under target: " + sales.GetSalesUnderTarget() + "\n");
         
         label_YearsProcessed.setText("Years Processed: " + sales.GetYearsProcessed());
    }
    
    //Save method
    private void save() {
        if (txtArea_Display.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please load data first!");
            return;
        }
        
        try (FileWriter writer = new FileWriter ("sales_log.txt")) {
            writer.write (txtArea_Display.getText());
            JOptionPane.showMessageDialog (this, "Product data saved to sales_log.txt");
        }
        catch (IOException e) {
            JOptionPane.showMessageDialog (this, "Could not save" + e.getMessage());
        }
    }
    

